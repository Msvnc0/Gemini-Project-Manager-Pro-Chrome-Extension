// RTL language codes
const RTL_LANGS = ['ar', 'he', 'fa', 'ur'];

let _gpmLang = 'en';

function gpmIsRTL() {
  return RTL_LANGS.includes(_gpmLang);
}

function gpmSetLang(lang) {
  _gpmLang = GPM_STRINGS[lang] ? lang : 'en';
  // Update direction attribute for RTL support
  const dir = gpmIsRTL() ? 'rtl' : 'ltr';
  if (typeof document !== 'undefined') {
    // Set dir on the GPM container if it exists
    if (typeof GPM_STATE !== 'undefined' && GPM_STATE.container) {
      GPM_STATE.container.setAttribute('dir', dir);
    }
    // Set dir on modal host shadow root if it exists
    if (typeof GPM_STATE !== 'undefined' && GPM_STATE.modalHost) {
      GPM_STATE.modalHost.setAttribute('dir', dir);
    }
  }
}

function t(key) {
  return GPM_STRINGS[_gpmLang]?.[key] || GPM_STRINGS['en']?.[key] || key;
}

/**
 * Get display name for a language in the dropdown.
 * Shows native name + translated name in parentheses if different.
 * e.g. "Deutsch (German)" when UI is English, "Deutsch (Almanca)" when UI is Turkish.
 * @param {string} langCode — Language code (e.g. 'de', 'fr')
 * @returns {string} — Formatted display name
 */
function getLanguageDisplayName(langCode) {
  const nativeName = LANGUAGE_NATIVE_NAMES[langCode] || langCode;
  const translatedName = LANGUAGE_NAMES_IN[_gpmLang]?.[langCode] || LANGUAGE_NAMES_IN['en']?.[langCode];
  if (translatedName && translatedName !== nativeName) {
    return `${nativeName} (${translatedName})`;
  }
  return nativeName;
}

/**
 * Get all supported language options for rendering a dropdown.
 * Returns an array of { code, displayName } objects.
 * @returns {Array<{code: string, displayName: string}>}
 */
function getLanguageOptions() {
  return SUPPORTED_LANG_CODES.map((code) => ({
    code,
    displayName: getLanguageDisplayName(code),
  }));
}

/**
 * Detect the best matching supported language from the browser's language preferences.
 * Checks navigator.languages (ordered preference list) first, then navigator.language.
 * For each browser language:
 *   1. Try exact match (e.g. "pt-BR" → mapped via alias, or "de" → direct match)
 *   2. Try base language code match (e.g. "pt-BR" → "pt", "zh-TW" → "zh")
 * Falls back to 'en' if no supported language is found.
 *
 * @returns {string} — A supported language code (e.g. 'tr', 'de', 'en')
 */
function detectBrowserLanguage() {
  // Alias map for regional variants → supported codes
  const LANG_ALIASES = {
    'zh-cn': 'zh-CN',
    'zh-tw': 'zh-CN',
    'zh-hk': 'zh-CN',
    'zh-hans': 'zh-CN',
    'zh-hant': 'zh-CN',
    zh: 'zh-CN',
    'pt-br': 'pt',
    'pt-pt': 'pt',
    'es-mx': 'es',
    'es-ar': 'es',
    'es-419': 'es',
    'fr-ca': 'fr',
    'fr-be': 'fr',
    'fr-ch': 'fr',
    'en-us': 'en',
    'en-gb': 'en',
    'en-au': 'en',
    'de-at': 'de',
    'de-ch': 'de',
    'ar-sa': 'ar',
    'ar-eg': 'ar',
    'bn-bd': 'bn',
    'bn-in': 'bn',
    'id-id': 'id',
    'it-it': 'it',
    'it-ch': 'it',
    'ja-jp': 'ja',
    'ko-kr': 'ko',
    'ru-ru': 'ru',
    'th-th': 'th',
    'tr-tr': 'tr',
    'vi-vn': 'vi',
    'hi-in': 'hi',
  };

  const browserLangs =
    typeof navigator !== 'undefined' && navigator.languages && navigator.languages.length > 0
      ? [...navigator.languages]
      : typeof navigator !== 'undefined' && navigator.language
        ? [navigator.language]
        : [];

  for (const rawLang of browserLangs) {
    const lang = rawLang.toLowerCase().trim();

    // 1. Direct match against supported codes
    if (SUPPORTED_LANG_CODES.includes(lang)) {
      return lang;
    }

    // 2. Check alias map (e.g. "zh-cn" → "zh")
    if (LANG_ALIASES[lang]) {
      return LANG_ALIASES[lang];
    }

    // 3. Base language code match (e.g. "pt-BR" → "pt")
    const baseLang = lang.split('-')[0];
    if (SUPPORTED_LANG_CODES.includes(baseLang)) {
      return baseLang;
    }
  }

  return 'en';
}
